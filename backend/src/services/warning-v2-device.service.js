const { randomUUID, createHash, timingSafeEqual } = require("node:crypto");
const { FieldValue } = require("firebase-admin/firestore");
const c = require("./flood-warning-v2-contract");
const { gpsBody, evaluatePosition } = require("./warning-v2-evaluation");

const DEVICE_COLLECTIONS = Object.freeze({ devices: "warning_v2_devices", registrations: "warning_v2_device_registrations",
  tokens: "warning_v2_token_claims", locations: "warning_v2_locations", events: "warning_v2_location_events" });
const digest = (value) => createHash("sha256").update(value).digest("hex");
function badDevice() { throw c.warningError("INVALID_DEVICE_DATA", "Invalid device registration or installation proof", 400); }
function uuid(value) { if (typeof value !== "string" || !/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value)) badDevice(); return value.toLowerCase(); }
function proofHash(value) {
  // Canonical base64url encoding of 32..64 cryptographically random bytes (generated by the app).
  if (typeof value !== "string" || !/^[A-Za-z0-9_-]{43,86}$/.test(value)) badDevice();
  const decoded = Buffer.from(value, "base64url");
  if (decoded.length < 32 || decoded.length > 64 || decoded.toString("base64url") !== value) badDevice();
  return digest(value);
}
function changed() { throw c.warningError("DEVICE_BINDING_CHANGED", "Device binding changed; reconcile this installation before continuing", 409); }
function checkProof(device, hash) {
  if (typeof device.secretHash !== "string" || device.secretHash.length !== hash.length ||
      !timingSafeEqual(Buffer.from(device.secretHash), Buffer.from(hash))) {
    throw c.warningError("INSTALLATION_PROOF_INVALID", "Installation proof is invalid", 403);
  }
}
function registrationBody(body) {
  const keys = ["platform", "fcmToken", "notificationPermission", "registrationId", "expectedBindingId", "expectedRevision"];
  if (!body || typeof body !== "object" || Array.isArray(body) || Object.keys(body).length !== keys.length ||
      Object.keys(body).some((key) => !keys.includes(key)) || body.platform !== "android" ||
      !["granted", "denied", "unknown"].includes(body.notificationPermission) ||
      (body.fcmToken !== null && (typeof body.fcmToken !== "string" || !/^[\x21-\x7e]{1,4096}$/.test(body.fcmToken))) ||
      !Number.isSafeInteger(body.expectedRevision) || body.expectedRevision < 0) badDevice();
  return { platform: "android", fcmToken: body.fcmToken, notificationPermission: body.notificationPermission,
    registrationId: uuid(body.registrationId), expectedBindingId: body.expectedBindingId === null ? null : uuid(body.expectedBindingId),
    expectedRevision: body.expectedRevision };
}
function bindingHeaders(headers) {
  return { installationId: uuid(headers.installationId), bindingId: uuid(headers.bindingId), secretHash: proofHash(headers.secret) };
}
function checkBinding(device, actorId, headers, { allowRevoked = false } = {}) {
  if (!device) changed();
  checkProof(device, headers.secretHash);
  if (device.ownerId !== actorId || device.bindingId !== headers.bindingId || (!allowRevoked && !device.active)) changed();
}
function publicDevice(installationId, device) {
  return { installationId, bindingId: device.bindingId, revision: device.revision, platform: "android",
    notificationPermission: device.notificationPermission, pushEligible: device.active && device.notificationPermission === "granted" && !!device.fcmToken,
    updatedAt: device.updatedAt.toDate().toISOString() };
}

function createWarningDeviceService({ db, zonesService, clock = Date.now }) {
  const ref = (kind, id) => db.collection(DEVICE_COLLECTIONS[kind]).doc(id);
  async function resident(tx, actorId) {
    const snapshot = await tx.get(db.collection("users").doc(c.documentId(actorId, "AUTH_REQUIRED", 401)));
    if (!snapshot.exists) throw c.warningError("AUTH_REQUIRED", "Account no longer exists", 401);
    if (snapshot.data().isActive !== true) throw c.warningError("ACCOUNT_INACTIVE", "Account is inactive", 403);
    if (snapshot.data().role !== "resident") throw c.warningError("ROLE_FORBIDDEN", "Resident access required", 403);
  }
  const clearedSample = () => ({ ownerId: null, bindingId: null, sequence: 0, bodyHash: null, availability: "unavailable",
    reason: "no_fix", location: null, capturedAt: null, accuracyM: null, receivedAt: null });
  async function installation(actorId, installationId, secret) {
    installationId = uuid(installationId); const secretHash = proofHash(secret);
    return db.runTransaction(async (tx) => {
      await resident(tx, actorId); const saved = await tx.get(ref("devices", installationId));
      const device = saved.data(); if (device) checkProof(device, secretHash);
      return { installation: { installationId, bindingId: device?.bindingId ?? null, revision: device?.revision ?? 0,
        active: device?.active ?? false, boundToCurrentAccount: !!device?.active && device.ownerId === actorId } };
    });
  }
  async function register(actorId, installationId, secret, body) {
    installationId = uuid(installationId);
    const secretHash = proofHash(secret), data = registrationBody(body), mutationHash = c.hash(data), newBindingId = randomUUID();
    const deviceRef = ref("devices", installationId), receiptRef = ref("registrations", c.hash([installationId, data.registrationId]));
    await db.runTransaction(async (tx) => {
      await resident(tx, actorId);
      const saved = await tx.get(deviceRef), receipt = await tx.get(receiptRef), location = await tx.get(ref("locations", installationId));
      const old = saved.exists ? saved.data() : null;
      if (old) checkProof(old, secretHash);
      const same = old?.active && old.ownerId === actorId && old.registrationId === data.registrationId;
      // Retain registration receipts: an old login must never rebind after a newer login/logout.
      if (receipt.exists && !same) changed();
      if (same && old.lastMutationHash === mutationHash) return;
      if ((old?.bindingId ?? null) !== data.expectedBindingId || (old?.revision ?? 0) !== data.expectedRevision) changed();
      if (same && old.fcmToken === data.fcmToken && old.notificationPermission === data.notificationPermission) return;
      const newClaimRef = data.fcmToken ? ref("tokens", digest(data.fcmToken)) : null;
      const newClaim = newClaimRef ? await tx.get(newClaimRef) : null;
      const oldClaimRef = old?.fcmToken ? ref("tokens", digest(old.fcmToken)) : null;
      const oldClaim = oldClaimRef && oldClaimRef.path !== newClaimRef?.path ? await tx.get(oldClaimRef) : null;
      if (newClaim?.exists && newClaim.data().active && newClaim.data().installationId !== installationId) {
        throw c.warningError("DEVICE_TOKEN_CONFLICT", "Push token is linked to another installation; do not transfer it automatically", 409);
      }
      const bindingId = same ? old.bindingId : newBindingId;
      const device = { ...data, ownerId: actorId, bindingId, secretHash, active: true,
        revision: (old?.revision ?? 0) + 1, lastMutationHash: mutationHash, updatedAt: FieldValue.serverTimestamp() };
      delete device.expectedBindingId; delete device.expectedRevision;
      if (saved.exists) tx.update(deviceRef, device); else tx.create(deviceRef, device);
      if (!receipt.exists) tx.create(receiptRef, { installationId, registrationId: data.registrationId, ownerId: actorId, bindingId,
        createdAt: FieldValue.serverTimestamp() });
      if (newClaimRef) {
        const claim = { installationId, bindingId, active: true, updatedAt: FieldValue.serverTimestamp() };
        if (newClaim.exists) tx.update(newClaimRef, claim); else tx.create(newClaimRef, claim);
      }
      if (oldClaim?.exists && oldClaim.data().installationId === installationId) {
        tx.update(oldClaimRef, { active: false, bindingId: null, updatedAt: FieldValue.serverTimestamp() });
      }
      if (!same) {
        const sampleRef = ref("locations", installationId);
        if (location.exists) tx.update(sampleRef, clearedSample()); else tx.create(sampleRef, clearedSample());
      }
    });
    // Read again in a guarded transaction: never return a different account's device after a race.
    return db.runTransaction(async (tx) => {
      await resident(tx, actorId); const device = (await tx.get(deviceRef)).data();
      checkProof(device, secretHash);
      if (!device.active || device.ownerId !== actorId || device.registrationId !== data.registrationId) changed();
      return { device: publicDevice(installationId, device) };
    });
  }
  async function unregister(actorId, installationId, headers) {
    const h = bindingHeaders(headers); if (uuid(installationId) !== h.installationId) badDevice();
    return db.runTransaction(async (tx) => {
      await resident(tx, actorId);
      const deviceRef = ref("devices", h.installationId), device = (await tx.get(deviceRef)).data();
      checkBinding(device, actorId, h, { allowRevoked: true });
      if (!device.active) return { installationId: h.installationId, bindingId: h.bindingId, unbound: true };
      const tokenRef = device.fcmToken ? ref("tokens", digest(device.fcmToken)) : null;
      const claim = tokenRef ? await tx.get(tokenRef) : null;
      const locationRef = ref("locations", h.installationId), location = await tx.get(locationRef);
      tx.update(deviceRef, { active: false, fcmToken: null, revision: device.revision + 1, updatedAt: FieldValue.serverTimestamp() });
      if (claim?.exists && claim.data().installationId === h.installationId && claim.data().bindingId === h.bindingId) {
        tx.update(tokenRef, { active: false, bindingId: null, updatedAt: FieldValue.serverTimestamp() });
      }
      if (location.exists) tx.update(locationRef, clearedSample());
      return { installationId: h.installationId, bindingId: h.bindingId, unbound: true };
    });
  }
  async function upload(actorId, headers, body) {
    const h = bindingHeaders(headers), data = gpsBody(body, clock()), bodyHash = c.hash(data);
    await db.runTransaction(async (tx) => {
      await resident(tx, actorId);
      const device = (await tx.get(ref("devices", h.installationId))).data(); checkBinding(device, actorId, h);
      const locationRef = ref("locations", h.installationId), previous = await tx.get(locationRef), old = previous.data();
      if (old?.bindingId === h.bindingId && old.sequence >= data.sequence) {
        if (old.sequence === data.sequence && old.bodyHash === bodyHash) return;
        throw c.warningError("LOCATION_SEQUENCE_CONFLICT", "Location sequence is no longer current", 409);
      }
      // A sample may have expired while waiting for locks. Save its original capture time; never refresh it on retry.
      const sample = { ...data, ownerId: actorId, bindingId: h.bindingId, bodyHash, receivedAt: FieldValue.serverTimestamp() };
      if (previous.exists) tx.update(locationRef, sample); else tx.create(locationRef, sample);
      tx.create(ref("events", c.hash([h.installationId, h.bindingId, data.sequence])), {
        installationId: h.installationId, bindingId: h.bindingId, residentId: actorId, sequence: data.sequence,
        kind: "location_changed", status: "pending", createdAt: FieldValue.serverTimestamp(),
      });
    });
    return evaluation(actorId, h, true);
  }
  async function evaluation(actorId, headers, parsed = false) {
    const h = parsed ? headers : bindingHeaders(headers);
    // Fail auth/proof before loading public but potentially large region data.
    await db.runTransaction(async (tx) => {
      await resident(tx, actorId); checkBinding((await tx.get(ref("devices", h.installationId))).data(), actorId, h);
    });
    const zones = await zonesService.load();
    return db.runTransaction(async (tx) => {
      await resident(tx, actorId); checkBinding((await tx.get(ref("devices", h.installationId))).data(), actorId, h);
      const saved = await tx.get(ref("locations", h.installationId));
      const alerts = await tx.get(db.collection("flood_alerts").where("schemaVersion", "==", 2));
      const current = saved.data();
      const sample = current?.bindingId === h.bindingId && current.ownerId === actorId ? {
        ...current, receivedAt: current.receivedAt?.toDate().toISOString() ?? null,
      } : null;
      return { evaluation: evaluatePosition({ sample, zones,
        activeAlertIds: alerts.docs.filter((s) => s.data().status === "active").map((s) => s.id).sort(),
        now: clock(), installationId: h.installationId, bindingId: h.bindingId }) };
    });
  }
  return { installation, register, unregister, upload, evaluation };
}
module.exports = { DEVICE_COLLECTIONS, createWarningDeviceService };
